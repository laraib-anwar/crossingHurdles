#!/usr/bin/env python3
"""Reference A for REGIMEN_SPEC (independent implementation).

Linear elimination (Vmax = 0): closed form. Each dose-free segment is advanced with the
matrix exponential of the augmented system z = [x, AUC, R] (scipy.linalg.expm, which needs no
diagonalisation, so the repeated eigenvalues of transit chains are handled exactly).

Saturable elimination (Vmax > 0): a Taylor-series integrator of order P_ORDER whose
coefficients are generated by automatic differentiation of the right-hand side (the
Michaelis-Menten term w = c/(Km + c) is expanded with the quotient recurrence), with
coefficient-based step control, and the variational equations expanded the same way for the
period-map Jacobian.

Events (IV boluses, lagged oral arrivals, infusion starts/ends, query times, cycle ends) are
segment boundaries, so every restart is exact. Periodic steady state: Newton on the period
map with the propagated Jacobian. Extrema and crossings: bracketed from a fine node grid of
the exact derivatives dC/dt and d2C/dt2 (computed from the ODE right-hand side), then
polished by Brent's method and a Newton step.
"""
import argparse
import json
import math
import sys
import time

import numpy as np
from scipy.linalg import expm
from scipy.optimize import brentq

P_ORDER = 28          # Taylor order
TAYLOR_TOL = 1e-17    # relative size of the last retained Taylor terms
N_CHECK = 60          # cycles checked for n_cycles_to_steady (guarantee 4)


# ----------------------------------------------------------------------------- model
class Model:
    def __init__(self, reg, cl_override=None, vmax_override=None):
        m = reg["model"]
        self.V1 = float(m["V1"])
        self.CL = float(m["CL"]) if cl_override is None else float(cl_override)
        self.Vmax = float(m["Vmax"]) if vmax_override is None else float(vmax_override)
        self.Km = float(m["Km"])
        per = m["peripheral"]
        n = 1 + len(per)
        self.forms = {}
        for f in reg["formulations"]:
            nt = int(f["n_transit"])
            self.forms[int(f["id"])] = dict(F=float(f["F"]), ka=float(f["ka"]),
                                            tlag=float(f["tlag"]), nt=nt,
                                            ktr=float(f["ktr"]), first=n, depot=n + nt)
            n += nt + 1
        L = np.zeros((n, n))
        V1 = self.V1
        L[0, 0] = -self.CL / V1
        for k, p in enumerate(per):
            Q, V = float(p["Q"]), float(p["V"])
            i = 1 + k
            L[0, 0] -= Q / V1
            L[0, i] += Q / V
            L[i, 0] += Q / V1
            L[i, i] -= Q / V
        for f in self.forms.values():
            for j in range(f["nt"]):
                idx = f["first"] + j
                L[idx, idx] -= f["ktr"]
                if j > 0:
                    L[idx, idx - 1] += f["ktr"]
            d = f["depot"]
            L[d, d] -= f["ka"]
            if f["nt"] > 0:
                L[d, d - 1] += f["ktr"]
            L[0, d] += f["ka"]
        self.L = L
        self.n = n
        self.linear = self.Vmax == 0.0
        lam = float(np.max(np.abs(np.linalg.eigvals(L)))) if n else 1.0
        if not self.linear:
            lam = max(lam, self.Vmax / (self.Km * V1) + self.CL / V1)
        self.lam = max(lam, 1e-3)
        self.hgrid = min(0.05, 0.25 / self.lam)

    # right-hand side and the exact first/second derivatives of C, vectorised over rows
    def rhs(self, X, R):
        X = np.atleast_2d(X)
        f = X @ self.L.T
        f[:, 0] += R
        if not self.linear:
            c = X[:, 0] / self.V1
            f[:, 0] -= self.Vmax * c / (self.Km + c)
        return f

    def dC(self, X, R):
        return self.rhs(X, R)[:, 0] / self.V1

    def d2C(self, X, R):
        X = np.atleast_2d(X)
        f = self.rhs(X, R)
        g = (f @ self.L.T)[:, 0]
        if not self.linear:
            c = X[:, 0] / self.V1
            g -= self.Vmax * self.Km / (self.V1 * (self.Km + c) ** 2) * f[:, 0]
        return g / self.V1


# ----------------------------------------------------------------------------- linear propagator
class LinearDense:
    def __init__(self, prop, x0, R, length):
        self.prop, self.x0, self.R, self.length = prop, np.array(x0, dtype=float), R, length
        self.z0 = np.concatenate([self.x0, [0.0, R]])
        zend = prop.E(length) @ self.z0
        self.x_end = zend[:prop.n].copy()
        self.auc = zend[prop.n]

    def state(self, tau):
        if tau <= 0.0:
            return self.x0.copy()
        if tau >= self.length:
            return self.x_end.copy()
        return (expm(self.prop.A * tau) @ self.z0)[:self.prop.n]

    def nodes(self, hgrid):
        N = max(2, int(math.ceil(self.length / hgrid)))
        h = self.length / N
        M = self.prop.E(h)
        Z = np.empty((N + 1, self.prop.n + 2))
        z = self.z0.copy()
        Z[0] = z
        for i in range(1, N):
            z = M @ z
            Z[i] = z
        taus = np.linspace(0.0, self.length, N + 1)
        X = Z[:, :self.prop.n]
        X[N] = self.x_end
        return taus, X


class LinearProp:
    kind = "expm"

    def __init__(self, model):
        n = model.n
        self.n = n
        A = np.zeros((n + 2, n + 2))
        A[:n, :n] = model.L
        A[0, n + 1] = 1.0            # infusion rate R enters A1
        A[n, 0] = 1.0 / model.V1     # d AUC / dt = C
        self.A = A
        self.cache = {}

    def E(self, h):
        M = self.cache.get(h)
        if M is None:
            M = expm(self.A * h)
            if len(self.cache) < 4096:
                self.cache[h] = M
        return M

    def segment(self, x, R, length, dense=False, Y=None):
        if dense:
            seg = LinearDense(self, x, R, length)
            x_end, auc = seg.x_end, seg.auc
        else:
            seg = None
            zend = self.E(length) @ np.concatenate([x, [0.0, R]])
            x_end, auc = zend[:self.n], zend[self.n]
        if Y is not None:
            Y = self.E(length)[:self.n, :self.n] @ Y
        return x_end, auc, seg, Y


# ----------------------------------------------------------------------------- Taylor propagator
class TaylorDense:
    def __init__(self, x0, R, length, steps, x_end, auc):
        self.x0, self.R, self.length, self.steps = x0, R, length, steps
        self.starts = np.array([s[0] for s in steps]) if steps else np.zeros(1)
        self.x_end, self.auc = x_end, auc

    @staticmethod
    def horner(X, tau):
        acc = X[-1].copy()
        for k in range(X.shape[0] - 2, -1, -1):
            acc = acc * tau + X[k]
        return acc

    def state(self, tau):
        if tau <= 0.0:
            return self.x0.copy()
        if tau >= self.length or not self.steps:
            return self.x_end.copy()
        i = int(np.searchsorted(self.starts, tau, side="right")) - 1
        i = max(0, min(i, len(self.steps) - 1))
        t0, h, X = self.steps[i]
        return self.horner(X, tau - t0)

    def nodes(self, hgrid):
        taus, rows = [], []
        if not self.steps:
            return np.array([0.0, self.length]), np.vstack([self.x0, self.x_end])
        for (t0, h, X) in self.steps:
            m = max(1, int(math.ceil(h / hgrid)))
            loc = np.arange(m) * (h / m)
            acc = np.tile(X[-1], (m, 1))
            for k in range(X.shape[0] - 2, -1, -1):
                acc = acc * loc[:, None] + X[k]
            taus.append(t0 + loc)
            rows.append(acc)
        taus.append(np.array([self.length]))
        rows.append(self.x_end[None, :])
        return np.concatenate(taus), np.vstack(rows)


class TaylorProp:
    kind = "taylor"

    def __init__(self, model, order=P_ORDER, tol=TAYLOR_TOL, hscale=1.0, hmax=4.0, scale_floor=1e-6):
        self.m = model
        self.scale_floor = scale_floor  # absolute amount floor (mg) for the step-size scale
        self.n = model.n
        self.p = order
        self.tol = tol
        self.hscale = hscale
        self.hmax = hmax
        self.nsteps = 0

    def coeffs(self, x0, R, Y0=None):
        m, p, n = self.m, self.p, self.n
        L = m.L
        iV1, Vmax, Km = 1.0 / m.V1, m.Vmax, m.Km
        X = np.empty((p + 1, n))
        X[0] = x0
        c = np.zeros(p + 1)
        w = np.zeros(p + 1)
        c[0] = x0[0] * iV1
        u0 = Km + c[0]
        w[0] = c[0] / u0
        jac = Y0 is not None
        if jac:
            Yc = np.empty((p + 1, n, n))
            Yc[0] = Y0
            s = np.zeros(p + 1)
            q = np.zeros(p + 1)
            s[0] = 1.0 / u0
            q[0] = Km * s[0] * s[0]
            kV = Vmax * iV1
        for k in range(p):
            if k > 0:
                c[k] = X[k, 0] * iV1
                w[k] = (c[k] - np.dot(c[1:k + 1], w[k - 1::-1])) / u0
                if jac:
                    s[k] = -np.dot(c[1:k + 1], s[k - 1::-1]) / u0
                    q[k] = Km * np.dot(s[:k + 1], s[k::-1])
            f = L @ X[k]
            if k == 0:
                f[0] += R
            f[0] -= Vmax * w[k]
            X[k + 1] = f / (k + 1)
            if jac:
                G = L @ Yc[k]
                G[0, :] -= kV * (q[:k + 1] @ Yc[k::-1, 0, :])
                Yc[k + 1] = G / (k + 1)
        return X, (Yc if jac else None)

    def choose_h(self, X):
        p = self.p
        s0 = max(np.max(np.abs(X[0])), self.scale_floor)
        h = math.inf
        for k in (p - 1, p):
            nk = np.max(np.abs(X[k]))
            if nk > 0.0:
                h = min(h, (self.tol * s0 / nk) ** (1.0 / k))
        return min(h * self.hscale, self.hmax)

    def segment(self, x, R, length, dense=False, Y=None):
        t = 0.0
        steps = [] if dense else None
        auc = 0.0
        x = x.copy()
        x_init = x.copy()
        p = self.p
        kk = np.arange(p + 1)
        while t < length:
            X, Yc = self.coeffs(x, R, Y)
            h = self.choose_h(X)
            rem = length - t
            if h >= rem or rem - h < 1e-12 * max(1.0, length):
                h = rem
            if dense:
                steps.append((t, h, X))
            x = TaylorDense.horner(X, h)
            auc += float(np.sum(X[:, 0] * h ** (kk + 1) / (kk + 1))) / self.m.V1
            if Y is not None:
                acc = Yc[-1].copy()
                for k in range(p - 1, -1, -1):
                    acc = acc * h + Yc[k]
                Y = acc
            self.nsteps += 1
            t = t + h if h != rem else length
        seg = TaylorDense(x_init, R, length, steps, x.copy(), auc) if dense else None
        return x, auc, seg, Y


# ----------------------------------------------------------------------------- event engine
def run_events(prop, x0, t0, t1, impulses, infusions, obs=(), dense_until=None, Y=None):
    """Advance from the left limit x0 at t0 to the left limit at t1.

    impulses: (t, index, amount), applied at t (right-continuity); impulses at t1 are not applied.
    infusions: (t_start, t_end, rate) active on [t_start, t_end).
    Returns final state, Jacobian (if Y given), dict of left/right states at obs times,
    cumulative AUC at each breakpoint, and the dense segments (a, b, R, x_a, seg) for b <= dense_until.
    """
    pts = {t0, t1}
    for (t, _, _) in impulses:
        if t0 <= t <= t1:
            pts.add(t)
    for (ts, te, _) in infusions:
        if t0 < ts < t1:
            pts.add(ts)
        if t0 < te < t1:
            pts.add(te)
    for t in obs:
        if t0 <= t <= t1:
            pts.add(t)
    B = sorted(pts)
    imp_at = {}
    for (t, i, a) in impulses:
        if t0 <= t < t1:
            imp_at.setdefault(t, []).append((i, a))
    obs_set = set(obs)
    left, right, cum_auc = {}, {}, {}
    segs = []
    x = np.array(x0, dtype=float)
    auc = 0.0
    for j, b in enumerate(B):
        if b in obs_set:
            left[b] = x.copy()
        for (i, a) in imp_at.get(b, ()):
            x[i] += a
        if b in obs_set:
            right[b] = x.copy()
        cum_auc[b] = auc
        if j == len(B) - 1:
            break
        nb = B[j + 1]
        mid = 0.5 * (b + nb)
        R = 0.0
        for (ts, te, r) in infusions:
            if ts <= mid < te:
                R += r
        dense = dense_until is not None and nb <= dense_until
        xa = x.copy()
        x, dauc, seg, Y = prop.segment(x, R, nb - b, dense=dense, Y=Y)
        x = np.array(x, dtype=float)  # private copy: impulses below must not alias segment data
        if dense:
            segs.append((b, nb, R, xa, seg))
        auc += dauc
    return x, Y, left, right, cum_auc, segs


def actual_events(reg, model, t_end):
    imp, inf = [], []

    def add(t, d):
        r = d["route"]
        a = float(d["amount"])
        if r == "iv_bolus":
            imp.append((t, 0, a))
        elif r == "oral":
            f = model.forms[int(d["formulation"])]
            idx = f["first"] if f["nt"] > 0 else f["depot"]
            imp.append((t + f["tlag"], idx, f["F"] * a))
        elif r == "iv_infusion":
            dur = float(d["duration"])
            inf.append((t, t + dur, a / dur))
        else:
            raise ValueError(r)

    for d in reg["loading_doses"]:
        add(float(d["time"]), d)
    mt = reg["maintenance"]
    start, P = float(mt["start"]), float(mt["period"])
    m = 0
    while start + m * P <= t_end:
        for d in mt["doses"]:
            add(start + m * P + float(d["offset"]), d)
        m += 1
    return imp, inf


def periodic_events(reg, model):
    """Events of one period of the maintenance-only periodic solution, in phase [0, P)."""
    mt = reg["maintenance"]
    P = float(mt["period"])
    imp, inf = [], []
    for d in mt["doses"]:
        o = float(d["offset"])
        a = float(d["amount"])
        r = d["route"]
        if r == "iv_bolus":
            imp.append((o, 0, a))
        elif r == "oral":
            f = model.forms[int(d["formulation"])]
            idx = f["first"] if f["nt"] > 0 else f["depot"]
            ph = o + f["tlag"]
            while ph >= P:
                ph -= P
            imp.append((ph, idx, f["F"] * a))
        else:
            dur = float(d["duration"])
            rate = a / dur
            e = o + dur
            bps = {0.0, P, o, e - math.floor(e / P) * P}
            bps = sorted(b for b in bps if 0.0 <= b <= P)
            for lo, hi in zip(bps[:-1], bps[1:]):
                if hi <= lo:
                    continue
                mid = 0.5 * (lo + hi)
                cnt = math.floor((mid - o) / P) - math.floor((mid - o - dur) / P)
                if cnt > 0:
                    inf.append((lo, hi, rate * cnt))
    return imp, inf


def cycles_until_periodic(reg, model):
    mt = reg["maintenance"]
    P = float(mt["period"])
    K = 1
    for d in mt["doses"]:
        o = float(d["offset"])
        if d["route"] == "oral":
            span = model.forms[int(d["formulation"])]["tlag"]
        elif d["route"] == "iv_infusion":
            span = float(d["duration"])
        else:
            span = 0.0
        K = max(K, int(math.floor((o + span) / P)) + 1)
    return max(K, 2)


# ----------------------------------------------------------------------------- segment analysis
def _brent(g, a, b, ga, gb):
    if ga == 0.0:
        return a
    if gb == 0.0:
        return b
    fa, fb = g(a), g(b)
    if fa == 0.0:
        return a
    if fb == 0.0:
        return b
    if (fa < 0.0) == (fb < 0.0):
        # node values bracketed a root but the exact re-evaluation does not: the root sits
        # within rounding of an end point
        return a if abs(fa) <= abs(fb) else b
    return brentq(g, a, b, xtol=1e-14, rtol=8.9e-16, maxiter=300)


def _newton_polish(r, g, dg, a, b):
    try:
        gr = g(r)
        d = dg(r)
        if d != 0.0 and np.isfinite(d):
            r2 = r - gr / d
            if a <= r2 <= b and abs(g(r2)) <= abs(gr):
                return r2
    except Exception:
        pass
    return r


def critical_points(model, seg, R, hgrid):
    taus, X = seg.nodes(hgrid)
    d1 = model.dC(X, R)
    d2 = model.d2C(X, R)

    def g1(t):
        return float(model.dC(seg.state(t), R)[0])

    def g2(t):
        return float(model.d2C(seg.state(t), R)[0])

    roots = []
    for i in range(len(taus) - 1):
        a, b = taus[i], taus[i + 1]
        ga, gb = d1[i], d1[i + 1]
        if (ga < 0.0 < gb) or (ga > 0.0 > gb):
            r = _brent(g1, a, b, ga, gb)
            roots.append(_newton_polish(r, g1, g2, a, b))
        elif (d2[i] < 0.0 < d2[i + 1]) or (d2[i] > 0.0 > d2[i + 1]):
            # dC/dt has an interior extremum here; if it changes sign there are two roots
            tm = _brent(g2, a, b, d2[i], d2[i + 1])
            gm = g1(tm)
            if (ga > 0.0 and gm < 0.0) or (ga < 0.0 and gm > 0.0):
                r1 = _brent(g1, a, tm, ga, gm)
                r2 = _brent(g1, tm, b, gm, gb)
                roots += [_newton_polish(r1, g1, g2, a, tm), _newton_polish(r2, g1, g2, tm, b)]
    roots = [r for r in roots if 0.0 < r < seg.length]
    return sorted(roots)


def analyze_segments(model, segs, levels=None, info=None, c_left0=0.0):
    """Candidates for extrema (time, value) and, if levels given, time inside [low, high].

    If info is a dict it is filled with diagnostic data used to check the spec guarantees:
    local maxima (interior critical points with C'' < 0, post-bolus values, kinks with
    C'(t-) >= 0 >= C'(t+), a closed right end with C'(t-) >= 0), |dC/dt| at every level
    crossing, and pre/post-bolus concentrations.
    """
    cands = []
    tin = 0.0
    locmax, crossings, bounds = [], [], []
    for (a, b, R, xa, seg) in segs:
        L = b - a
        if L <= 0.0:
            continue
        C = lambda t: float(seg.state(t)[0]) / model.V1
        crit = critical_points(model, seg, R, model.hgrid)
        c0 = float(xa[0]) / model.V1
        c1 = float(seg.x_end[0]) / model.V1
        pts = [(0.0, c0)] + [(t, C(t)) for t in crit] + [(L, c1)]
        for (t, v) in pts:
            cands.append((a + t, v))
        if info is not None:
            for t in crit:
                st = seg.state(t)
                d2 = float(model.d2C(st, R)[0])
                if d2 < 0.0:
                    locmax.append((a + t, float(st[0]) / model.V1, "interior", d2))
            bounds.append((a, c0, float(model.dC(xa, R)[0]), b, c1, float(model.dC(seg.x_end, R)[0])))
        if levels is not None:
            low, high = levels
            brk = [p[0] for p in pts]
            for lev in (low, high):
                for (ta, va), (tb, vb) in zip(pts[:-1], pts[1:]):
                    ga, gb = va - lev, vb - lev
                    if (ga < 0.0 < gb) or (ga > 0.0 > gb):
                        g = lambda t, lev=lev: C(t) - lev
                        r = _brent(g, ta, tb, ga, gb)
                        dg = lambda t: float(model.dC(seg.state(t), R)[0])
                        r = _newton_polish(r, g, dg, ta, tb)
                        brk.append(r)
                        crossings.append((a + r, lev, dg(r)))
            brk = sorted(set(brk))
            for lo, hi in zip(brk[:-1], brk[1:]):
                if hi > lo:
                    v = C(0.5 * (lo + hi))
                    if low <= v <= high:
                        tin += hi - lo
    if info is not None:
        jumps = []
        # junctions between consecutive segments
        for k, (a, c0, d0, b, c1, d1) in enumerate(bounds):
            if k == 0:
                if c0 - c_left0 > 1e-12 * max(abs(c0), abs(c_left0)):
                    jumps.append((a, c_left0, c0))
                    locmax.append((a, c0, "post-bolus", d0))
                elif d0 < 0.0:
                    locmax.append((a, c0, "left-end", d0))
            if k + 1 < len(bounds):
                (a2, c02, d02, _, _, _) = bounds[k + 1]
                if c02 - c1 > 1e-12 * max(abs(c1), abs(c02)):
                    jumps.append((a2, c1, c02))
                    locmax.append((a2, c02, "post-bolus", d02))
                elif d1 >= 0.0 >= d02 and not (d1 == 0.0 and d02 == 0.0):
                    locmax.append((b, c1, "kink", (d1, d02)))
            else:
                if d1 > 0.0:
                    locmax.append((b, c1, "right-end", d1))
        info["local_maxima"] = locmax
        info["crossings"] = crossings
        info["jumps"] = jumps
    return cands, tin


# ----------------------------------------------------------------------------- steady state
def period_map(prop, x, pimp, pinf, P, jac=False):
    Y = np.eye(prop.n) if jac else None
    xe, Y, _, _, _, _ = run_events(prop, x, 0.0, P, pimp, pinf, Y=Y)
    return xe, Y


def steady_state(reg, model, prop, diag):
    P = float(reg["maintenance"]["period"])
    pimp, pinf = periodic_events(reg, model)
    n = model.n
    if model.linear:
        x = np.zeros(n)
    else:
        # initial guess: linear model whose clearance matches the saturable one at the mean conc
        dose = 0.0
        for d in reg["maintenance"]["doses"]:
            a = float(d["amount"])
            dose += a * (model.forms[int(d["formulation"])]["F"] if d["route"] == "oral" else 1.0)
        rin = dose / P
        CL, Vm, Km = model.CL, model.Vmax, model.Km
        # CL c^2 + (CL Km + Vm - rin) c - rin Km = 0
        bq = CL * Km + Vm - rin
        cbar = (-bq + math.sqrt(bq * bq + 4.0 * CL * rin * Km)) / (2.0 * CL)
        lm = Model(reg, cl_override=CL + Vm / (Km + cbar), vmax_override=0.0)
        lp = LinearProp(lm)
        x = np.zeros(n)
        for _ in range(2):
            xe, Y = period_map(lp, x, pimp, pinf, P, jac=True)
            x = x - np.linalg.solve(Y - np.eye(n), xe - x)
    hist = []
    for it in range(60):
        xe, Y = period_map(prop, x, pimp, pinf, P, jac=True)
        F = xe - x
        res = np.max(np.abs(F)) / max(np.max(np.abs(x)), np.max(np.abs(xe)), 1e-300)
        hist.append(res)
        dx = -np.linalg.solve(Y - np.eye(n), F)
        lam = 1.0
        while True:
            xn = x + lam * dx
            if np.all(xn >= -1e-12 * np.max(np.abs(x) + 1.0)) or lam < 1e-3:
                break
            lam *= 0.5
        x = xn
        if np.max(np.abs(lam * dx)) <= 2e-16 * max(np.max(np.abs(x)), 1e-300) or (it >= 2 and res < 1e-15):
            break
    xe, _ = period_map(prop, x, pimp, pinf, P)
    res = float(np.max(np.abs(xe - x)) / np.max(np.abs(x)))
    diag["newton_residual_rel"] = res
    diag["newton_history"] = [float(h) for h in hist]
    diag["newton_iterations"] = len(hist)
    # dense pass over one period
    xe, _, _, _, _, segs = run_events(prop, x, 0.0, P, pimp, pinf, dense_until=P)
    w = reg["window"]
    sinfo = {}
    cands, tin = analyze_segments(model, segs, (float(w["low"]), float(w["high"])), info=sinfo,
                                  c_left0=float(x[0]) / model.V1)
    vals = [v for (_, v) in cands]
    diag["ss_info"] = sinfo
    return dict(x=x, trough=float(x[0]) / model.V1, cmax=max(vals), cmin=min(vals),
                tin=tin, pimp=pimp, pinf=pinf)


# ----------------------------------------------------------------------------- driver
def solve(reg, engine="auto", hscale=1.0, order=P_ORDER, diag=None):
    if diag is None:
        diag = {}
    t_start = time.time()
    model = Model(reg)
    if engine == "auto":
        engine = "expm" if model.linear else "taylor"
    amax = max(float(d["amount"]) for d in reg["loading_doses"] + reg["maintenance"]["doses"])
    prop = (LinearProp(model) if engine == "expm" else
            TaylorProp(model, order=order, hscale=hscale, scale_floor=1e-6 * amax))
    mt = reg["maintenance"]
    start, P = float(mt["start"]), float(mt["period"])
    H = float(reg["horizon"])
    qt = [float(t) for t in reg["query_times"]]
    K0 = cycles_until_periodic(reg, model)
    Kd = max(K0, int(math.ceil((H - start) / P - 1e-12)))
    t_end = start + Kd * P
    imp, inf = actual_events(reg, model, t_end)
    bounds = [start + k * P for k in range(1, Kd + 1)]
    obs = sorted(set(qt + [H] + bounds))
    xK, _, left, right, cum_auc, segs = run_events(prop, np.zeros(model.n), 0.0, t_end, imp, inf,
                                                   obs=obs, dense_until=H)
    if not np.all(np.isfinite(xK)):
        raise FloatingPointError("non-finite state")
    conc = [float(right[t][0]) / model.V1 for t in qt]
    auc = float(cum_auc[H])
    ainfo = {}
    cands, _ = analyze_segments(model, segs, info=ainfo)
    diag["actual_info"] = ainfo
    vmax_, tmax_ = -math.inf, None
    for (t, v) in cands:
        if t <= H and v > vmax_:
            vmax_, tmax_ = v, t
    ss = steady_state(reg, model, prop, diag)
    troughs = []
    for k in range(1, min(Kd, N_CHECK) + 1):
        tb = start + k * P
        troughs.append(float(left[tb][0]) / model.V1 if tb != t_end else float(xK[0]) / model.V1)
    x = xK.copy()
    for k in range(Kd + 1, N_CHECK + 1):
        x, _ = period_map(prop, x, ss["pimp"], ss["pinf"], P)
        troughs.append(float(x[0]) / model.V1)
    tr = ss["trough"]
    ok = [abs(t - tr) <= 0.01 * tr for t in troughs]
    ncyc = N_CHECK
    for n in range(N_CHECK, 0, -1):
        if ok[n - 1]:
            ncyc = n
        else:
            break
    margins = [abs(abs(t - tr) - 0.01 * tr) / tr for t in troughs]
    diag.update(engine=engine, runtime_s=time.time() - t_start, K0=K0, Kd=Kd,
                min_trough_margin_rel=float(min(margins)),
                taylor_steps=getattr(prop, "nsteps", None), hgrid=model.hgrid,
                troughs=troughs)
    report = {
        "regimen_id": reg["regimen_id"],
        "concentrations": conc,
        "auc": auc,
        "cmax": float(vmax_),
        "t_cmax": float(tmax_),
        "steady_state": {
            "cmax": float(ss["cmax"]),
            "cmin": float(ss["cmin"]),
            "trough": float(tr),
            "time_in_window": float(ss["tin"]),
            "n_cycles_to_steady": int(ncyc),
        },
    }
    return report, diag


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--regimen", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--engine", default="auto", choices=["auto", "expm", "taylor"])
    ap.add_argument("--hscale", type=float, default=1.0)
    ap.add_argument("--order", type=int, default=P_ORDER)
    ap.add_argument("--diag", default=None)
    a = ap.parse_args()
    with open(a.regimen, "r", encoding="utf-8") as fh:
        reg = json.load(fh)
    rep, diag = solve(reg, engine=a.engine, hscale=a.hscale, order=a.order)
    with open(a.output, "w", encoding="utf-8") as fh:
        json.dump(rep, fh, indent=1)
    if a.diag:
        with open(a.diag, "w", encoding="utf-8") as fh:
            json.dump(diag, fh, indent=1, default=float)
    return 0


if __name__ == "__main__":
    sys.exit(main())
